#2. Calcular el sueldo mensual de un operario conociendo la cantidad de horas trabajadas y el valor por hora.

cHoras = int(input("Ingrese la cantidad de horas trabajadas: "))
vHora = int(input("Ingrese el valor por hora: "))

sueldo = cHoras * vHora

print(f"El sueldo mensual es de {sueldo}")
